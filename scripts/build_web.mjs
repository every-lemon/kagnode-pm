/** Generate fingerprinted production assets separately from editable source. */
import { transform } from "esbuild";
import { createHash } from "node:crypto";
import { readFile, writeFile, mkdir, readdir, unlink } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check"),
  output = path.join(root, "web/generated"),
  expected = new Map(),
  constants = [];
for (const extension of ["js", "css"]) {
  const result = await transform(
    await readFile(path.join(root, "web/app." + extension), "utf8"),
    {
      loader: extension,
      minify: true,
      sourcemap: false,
      legalComments: "inline",
      target: ["es2022"],
      banner:
        "/* KagNode. PM · AGPL-3.0-only · github.com/every-lemon/kagnode-pm */",
    },
  );
  const digest = createHash("sha256")
      .update(result.code)
      .digest("hex")
      .slice(0, 16),
    name = `app.${digest}.${extension}`,
    symbol = extension.toUpperCase();
  expected.set(name, result.code);
  constants.push(
    `pub const ${symbol}_NAME: &str = "${name}";`,
    `#[rustfmt::skip]\npub const ${symbol}: &str = include_str!("../web/generated/${name}");`,
  );
}
const rust =
  "// Generated by scripts/build_web.mjs; edit web/app.js or web/app.css.\n" +
  constants.join("\n") +
  "\n";
if (check) {
  if (
    JSON.stringify((await readdir(output)).sort()) !==
    JSON.stringify([...expected.keys()].sort())
  )
    throw Error("Unexpected generated asset inventory");
  for (const [name, content] of expected)
    if ((await readFile(path.join(output, name), "utf8")) !== content)
      throw Error("Stale asset: " + name);
  if (
    (await readFile(path.join(root, "src/generated_assets.rs"), "utf8")) !==
    rust
  )
    throw Error("Stale generated asset references");
  console.log("Generated assets match editable source.");
} else {
  await mkdir(output, { recursive: true });
  for (const name of await readdir(output))
    if (!expected.has(name)) await unlink(path.join(output, name));
  for (const [name, content] of expected)
    await writeFile(path.join(output, name), content);
  await writeFile(path.join(root, "src/generated_assets.rs"), rust);
}
